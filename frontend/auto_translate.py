def get_replacement(text, es, en):
    text_esc = text.replace("'", "\\'")
    es_esc = es.replace("'", "\\'")
    en_esc = en.replace("'", "\\'")
    return f"{{{{ isZh ? '{text_esc}' : isEs ? '{es_esc}' : '{en_esc}' }}}}"

sorted_keys = sorted(TRANS.keys(), key=len, reverse=True)
modified_files = 0

for root, dirs, files in os.walk('src'):
    for file in files:
        if file.endswith('.vue'):
            filepath = os.path.join(root, file)
            with open(filepath, 'r', encoding='utf-8') as f:
                content = f.read()
            
            original_content = content
            
            for zh in sorted_keys:
                es, en = TRANS[zh]
                # 在纯文本（> 和 < 之间）替换
                pattern_text = re.compile(r'>\s*(' + re.escape(zh) + r')\s*<')
                content = pattern_text.sub('>' + get_replacement(zh, es, en) + '<', content)
                
                # 在属性（placeholder="..." 等）里替换
                pattern_attr = re.compile(r'(["\'])' + re.escape(zh) + r'\1')
                content = pattern_attr.sub(r'\1' + get_replacement(zh, es, en) + r'\1', content)

            if content != original_content:
                with open(filepath, 'w', encoding='utf-8') as f:
                    f.write(content)
                modified_files += 1

