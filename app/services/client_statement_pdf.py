def generate_client_statement(client: Client, orders: list[Order], payments: list[ClientPaymentRecord], lang: str = "zh") -> bytes:
    t = I18N.get(lang, I18N["en"])
    
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
    elements = []
    
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle('Title', parent=styles['Heading1'], fontName=FONT_NAME, fontSize=18, alignment=1, spaceAfter=10)
    normal_style = ParagraphStyle('Normal', parent=styles['Normal'], fontName=FONT_NAME, fontSize=10, leading=14)
    block_title_style = ParagraphStyle('BlockTitle', parent=styles['Normal'], fontName=FONT_NAME, fontSize=11, textColor=colors.HexColor("#1e40af"), spaceAfter=5, spaceBefore=15)
    
    elements.append(Paragraph(t["title"], title_style))
    elements.append(Paragraph(f"{t['date']}: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", ParagraphStyle('Center', parent=normal_style, alignment=1, textColor=colors.gray)))
    
    # 公司信息
    elements.append(Paragraph(t["company_info"], block_title_style))
    elements.append(Paragraph(t["company_desc"], normal_style))
    elements.append(Spacer(1, 10))
    
    # 客户档案
    elements.append(Paragraph(t["client_info"], block_title_style))
    c_data = [
        [Paragraph(f"{t['c_name']}: {client.name}", normal_style), 
         Paragraph(f"{t['c_store']}: {client.store_name or '-'}", normal_style)],
        [Paragraph(f"{t['c_phone']}: {client.phone or '-'}", normal_style), 
         Paragraph(f"{t['c_rif']}: {client.rif_or_cedula or '-'}", normal_style)],
        [Paragraph(f"{t['current_debt']}: <font color='red'>${client.debt:.2f}</font>", normal_style), 
         Paragraph("", normal_style)]
    ]
    c_table = Table(c_data, colWidths=[260, 260])
    c_table.setStyle(TableStyle([
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
    ]))
    elements.append(c_table)
    elements.append(Spacer(1, 15))
    
    # 往来明细
    transactions = []
    for order in orders:
        if order.status == "COMPLETED":
            transactions.append({
                "date_str": order.created_at.strftime("%Y-%m-%d"),
                "sort_key": order.created_at,
                "type": t["type_order"],
                "ref": order.order_no,
                "amount": order.total_usd,
            })
            
    for pay in payments:
        try:
            dt = datetime.strptime(pay.timestamp, "%Y-%m-%d %H:%M")
        except Exception:
            dt = datetime.now()
        transactions.append({
            "date_str": dt.strftime("%Y-%m-%d"),
            "sort_key": dt,
            "type": t["type_pay"],
            "ref": pay.reference_no or pay.payment_method,
            "amount": -pay.amount_usd,
        })
        
    transactions.sort(key=lambda x: x["sort_key"])
    
    table_data = [[
        Paragraph(f"{t['col_date']}", normal_style), 
        Paragraph(f"{t['col_type']}", normal_style), 
        Paragraph(f"{t['col_ref']}", normal_style), 
        Paragraph(f"{t['col_amount']}", normal_style)
    ]]
    
    total_debit = 0.0
    total_credit = 0.0
    
    for tx in transactions:
        amt = tx["amount"]
        amt_str = f"+{amt:.2f}" if amt > 0 else f"{amt:.2f}"
        if amt > 0: 
            total_debit += amt
        else: 
            total_credit += abs(amt)
            
        table_data.append([
            Paragraph(tx["date_str"], normal_style),
            Paragraph(tx["type"], normal_style),
            Paragraph(tx["ref"], normal_style),
            Paragraph(f"<font color='{'red' if amt>0 else 'green'}'>{amt_str}</font>", normal_style)
        ])
        
    table_data.append([
        Paragraph(f"{t['summary']}", normal_style),
        Paragraph("", normal_style),
        Paragraph(f"Debit: ${total_debit:.2f} / Credit: ${total_credit:.2f}", normal_style),
        Paragraph(f"${client.debt:.2f}", normal_style)
    ])
    
    detail_table = Table(table_data, colWidths=[80, 80, 200, 160], repeatRows=1)
    detail_table.setStyle(TableStyle([
        ('GRID', (0,0), (-1,-1), 0.5, colors.lightgrey),
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#f8fafc")),
        ('ALIGN', (3,0), (3,-1), 'RIGHT'),
        ('PADDING', (0,0), (-1,-1), 8),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('BACKGROUND', (0,-1), (-1,-1), colors.HexColor("#eff6ff")),
    ]))
    
    elements.append(detail_table)
    elements.append(Spacer(1, 20))
    elements.append(Paragraph(t["footer"], ParagraphStyle('Footer', parent=normal_style, alignment=1, textColor=colors.gray, fontSize=9)))
    
    doc.build(elements)
    return buffer.getvalue()
